from __future__ import annotations
from typing import Protocol
from app.models.config import Settings, Identity
from app.models.flow import Availability, Summary, Receipt

class Adapter(Protocol):
    supports_submit: bool
    async def prepare(self, config: Settings): ...
    async def is_open(self) -> bool: ...
    async def select_product(self, config: Settings): ...
    async def availability(self, config: Settings) -> list[Availability]: ...
    async def select_pickup(self, store: Availability, config: Settings): ...
    async def fill_customer(self, identity: Identity | None, config: Settings): ...
    async def select_payment(self, config: Settings) -> str: ...
    async def review(self, config: Settings) -> Summary: ...
    async def submit(self, config: Settings) -> Receipt: ...
    async def reconcile(self, config: Settings) -> Receipt | None: ...
